#!/usr/bin/env node
// Writes src/abi.ts from the Foundry artifact of DealEscrow.
//   node scripts/gen-abi.mjs          regenerate src/abi.ts
//   node scripts/gen-abi.mjs --check  exit 1 if src/abi.ts differs from what the artifact produces
// Run `forge build` in contracts/ first so the artifact exists.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, '..');
const repoRoot = resolve(pkgRoot, '../..');
const artifactPath = resolve(repoRoot, 'contracts/out/DealEscrow.sol/DealEscrow.json');
const outPath = resolve(pkgRoot, 'src/abi.ts');

export function render(abi) {
  const body = JSON.stringify(abi, null, 2);
  return [
    '// Generated by scripts/gen-abi.mjs from contracts/out/DealEscrow.sol/DealEscrow.json. Do not edit by hand.',
    '// Regenerate with `pnpm --filter @plug360/shared gen:abi` after `forge build` in contracts/.',
    '',
    `export const dealEscrowAbi = ${body} as const;`,
    '',
  ].join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  if (!existsSync(artifactPath)) {
    console.error(`missing ${relative(repoRoot, artifactPath)}: run \`forge build\` in contracts/ first`);
    process.exit(2);
  }
  const artifact = JSON.parse(readFileSync(artifactPath, 'utf8'));
  if (!Array.isArray(artifact.abi) || artifact.abi.length === 0) {
    console.error('artifact has no abi');
    process.exit(2);
  }
  const next = render(artifact.abi);
  if (check) {
    const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
    if (current !== next) {
      console.error('src/abi.ts is stale: run `pnpm --filter @plug360/shared gen:abi`');
      process.exit(1);
    }
    console.log('src/abi.ts matches the DealEscrow artifact');
    return;
  }
  writeFileSync(outPath, next);
  console.log(`wrote ${relative(repoRoot, outPath)} (${artifact.abi.length} entries)`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
